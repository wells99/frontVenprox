import assert from 'node:assert/strict'
import test from 'node:test'
import { createServer } from 'vite'
const server = await createServer({ server: { middlewareMode: true, hmr: false, ws: false }, appType: 'custom' })
let reminders
try { reminders = await server.ssrLoadModule('/src/features/bills/reminderDemo.ts') } finally { await server.close() }
const now = '2026-11-20T12:00'
const base = () => ({ rules: [], occurrences: [], sessions: [{ number: 27, cash: 1000 }], sales: [{ id: 'sale' }], creditEntries: [{ id: 'credit' }] })
const create = (overrides = {}) => ({ ruleId: 'r1', mode: 'create', scope: 'future', description: 'Conta teste', amountCents: 1000, dueAt: '2026-01-31T09:00', frequency: 'monthly', interval: 1, at: now, ...overrides })
const resolve = (state, occurrence = state.occurrences.find((item) => item.status === 'pending')) => ({ kind: 'resolve', occurrenceId: occurrence.id, expectedVersion: occurrence.version, expectedRuleVersion: state.rules.find((rule) => rule.id === occurrence.ruleId).version, at: now })
const edit = (state, changes = {}) => {
  const occurrence = state.occurrences.find((item) => item.status === 'pending')
  const rule = state.rules.find((item) => item.id === occurrence.ruleId)
  return { ruleId: rule.id, occurrenceId: occurrence.id, mode: 'edit', scope: 'occurrence', description: occurrence.description, amountCents: occurrence.amountCents, dueAt: occurrence.dueAt, frequency: rule.frequency, interval: rule.interval, expectedVersion: occurrence.version, expectedRuleVersion: rule.version, at: now, ...changes }
}
test('calendário mensal conserva dia 31 após mês curto; anual recupera 29 de fevereiro', () => {
  const monthly = create()
  assert.equal(reminders.occurrenceAt({ ...monthly, anchorAt: monthly.dueAt },1), '2026-02-28T09:00')
  assert.equal(reminders.occurrenceAt({ ...monthly, anchorAt: monthly.dueAt },2), '2026-03-31T09:00')
  assert.equal(reminders.occurrenceAt({ anchorAt: '2024-02-29T08:30', frequency: 'yearly', interval: 1 },1), '2025-02-28T08:30')
  assert.equal(reminders.occurrenceAt({ anchorAt: '2024-02-29T08:30', frequency: 'yearly', interval: 1 },4), '2028-02-29T08:30')
})
test('intervalos de calendário cruzam mês e ano mantendo hora da loja', () => {
  assert.equal(reminders.occurrenceAt({ anchorAt: '2026-12-30T23:10', frequency: 'daily', interval: 2 },1), '2027-01-01T23:10')
  assert.equal(reminders.occurrenceAt({ anchorAt: '2026-12-30T23:10', frequency: 'weekly', interval: 2 },1), '2027-01-13T23:10')
  assert.equal(reminders.localReminderNow(new Date('2026-11-21T01:00:00Z')), '2026-11-20T22:00')
  assert.equal(reminders.validReminderDate('2026-02-30T12:00'),false)
  assert.equal(reminders.validReminderDate('2026-11-20T24:00'),false)
})
test('cadastro e resolução não alteram caixa, vendas ou fiado e não duplicam intenção', () => {
  const state = base(), intent = create()
  const next = reminders.applyReminderSave(state,intent)
  assert.equal(next.rules.length,1); assert.equal(next.occurrences.length,1)
  assert.equal(next.sessions,state.sessions); assert.equal(next.sales,state.sales); assert.equal(next.creditEntries,state.creditEntries)
  assert.equal(reminders.applyReminderSave(next,intent),next)
  const resolved = reminders.applyReminderAction(next,resolve(next))
  assert.equal(resolved.occurrences.length,2)
  assert.equal(resolved.sessions,state.sessions)
  assert.equal(reminders.applyReminderAction(resolved,resolve(next)),resolved)
  assert.equal(resolved.occurrences.find((item) => item.status === 'pending').dueAt,'2026-02-28T09:00')
})
test('adiar preserva identidade, calendário e valores; a próxima data não deriva do adiamento', () => {
  const state = reminders.applyReminderSave(base(),create())
  const postponed = reminders.applyReminderSave(state,edit(state,{ mode:'postpone', dueAt:'2026-12-01T10:00' }))
  assert.equal(postponed.occurrences[0].id,state.occurrences[0].id)
  assert.equal(postponed.occurrences[0].scheduledAt,'2026-01-31T09:00')
  assert.equal(postponed.rules,state.rules)
  const next = reminders.applyReminderAction(postponed,resolve(postponed))
  assert.equal(next.occurrences.find((item) => item.status === 'pending').dueAt,'2026-02-28T09:00')
  assert.equal(reminders.applyReminderSave(state,edit(state,{ mode:'postpone', dueAt:'2026-02-01T10:00' })),state)
})
test('editar só a ocorrência preserva valores futuros; editar futuras conserva histórico resolvido', () => {
  const state = reminders.applyReminderSave(base(),create())
  const only = reminders.applyReminderSave(state,edit(state,{ description:'Exceção', amountCents:500 }))
  assert.equal(only.rules[0].amountCents,1000)
  const withNext = reminders.applyReminderAction(only,resolve(only))
  const old = withNext.occurrences.find((item) => item.status === 'resolved')
  assert.equal(old.description,'Exceção')
  const future = reminders.applyReminderSave(withNext,edit(withNext,{ scope:'future', description:'Série atualizada', amountCents:2000 }))
  assert.equal(future.occurrences.find((item) => item.status === 'resolved'),old)
  const march = reminders.applyReminderAction(future,resolve(future))
  assert.equal(march.occurrences.find((item) => item.status === 'pending').dueAt,'2026-03-31T09:00')
  assert.equal(march.occurrences.find((item) => item.status === 'pending').amountCents,2000)
})
test('alterar data da série reinicia referência sem colidir com identidades anteriores', () => {
  let state = reminders.applyReminderSave(base(),create())
  state = reminders.applyReminderAction(state,resolve(state))
  state = reminders.applyReminderSave(state,edit(state,{ scope:'future', dueAt:'2026-12-15T11:00' }))
  assert.equal(state.rules[0].generation,2)
  state = reminders.applyReminderAction(state,resolve(state))
  assert.equal(state.occurrences.find((item) => item.status === 'pending').dueAt,'2027-01-15T11:00')
  assert.equal(new Set(state.occurrences.map((item) => item.id)).size,state.occurrences.length)
})
test('interromper série mantém pendente e histórico; resolver depois não gera próxima', () => {
  const state = reminders.applyReminderSave(base(),create())
  const stopped = reminders.applyReminderAction(state,{ ...resolve(state),kind:'stop' })
  assert.equal(stopped.rules[0].active,false)
  assert.equal(stopped.occurrences,state.occurrences)
  const resolved = reminders.applyReminderAction(stopped,resolve(stopped))
  assert.equal(resolved.occurrences.length,1)
  assert.equal(resolved.occurrences[0].status,'resolved')
  assert.equal(reminders.applyReminderSave(stopped,edit(stopped,{ scope:'future' })),stopped)
})
test('vazio, data inválida, valor inválido, intervalo e versão bloqueiam mutações', () => {
  const state = base()
  for (const changes of [{ description:' ' },{ amountCents:-1 },{ amountCents:0.5 },{ dueAt:'2026-02-30T09:00' },{ interval:0 },{ interval:1.5 },{ frequency:'unknown' }]) assert.equal(reminders.applyReminderSave(state,create(changes)),state)
  const created = reminders.applyReminderSave(state,create())
  assert.equal(reminders.applyReminderSave(created,edit(created,{ expectedVersion:0 })),created)
  const resolved = reminders.applyReminderAction(created,resolve(created))
  assert.equal(reminders.applyReminderSave(resolved,{ ...edit(created),scope:'future' }),resolved)
  assert.equal(reminders.applyReminderAction(created,{ ...resolve(created),kind:'invalid' }),created)
  assert.equal(reminders.applyReminderSave(state,create({ amountCents:0 })).occurrences[0].amountCents,0)
})
test('avisos agrupam atrasadas e deduplicam sem descartar novo horário adiado', () => {
  let state = reminders.applyReminderSave(base(),create())
  state = reminders.applyReminderSave(state,create({ ruleId:'r2',dueAt:'2026-11-19T10:00' }))
  const seen = new Set()
  const first = reminders.collectReminderNotices(state.occurrences,now,seen)
  assert.equal(first.due.length,2)
  first.keys.forEach((key) => seen.add(key))
  assert.equal(reminders.collectReminderNotices(state.occurrences,now,seen).due.length,0)
  const postponed = reminders.applyReminderSave(state,edit(state,{mode:'postpone',dueAt:'2026-12-01T10:00'}))
  assert.equal(reminders.collectReminderNotices(postponed.occurrences,now,seen).due.length,0)
  assert.equal(reminders.collectReminderNotices(postponed.occurrences,'2026-12-01T10:00',seen).due.length,1)
})
